def main():
    dry = "--dry" in sys.argv
    total = 0
    for f in sorted(os.listdir(T)):
        if not f.endswith(".html"):
            continue
        p = os.path.join(T, f)
        t = io.open(p, encoding="utf-8").read()
        if not re.search(r'实际编译|实际运行核对|实际验证|实际编译产生', t):
            continue
        t2, n = t, 0
        # 同一文件里循环应用规则，直到不再命中（一条句子里可能套两层模式）
        for _round in range(4):
            hit = 0
            for pat, rep, _tag in RULES:
                t2, k = re.subn(pat, rep, t2)
                hit += k
            n += hit
            if hit == 0:
                break
        if t2 != t:
            total += n
            print("  %-34s 改 %2d 处" % (f, n))
            if not dry:
                io.open(p, "w", encoding="utf-8", newline="").write(t2)
    print()
    print("  合计修改 %d 处%s" % (total, "  [dry-run]" if dry else ""))


if __name__ == "__main__":
    main()
