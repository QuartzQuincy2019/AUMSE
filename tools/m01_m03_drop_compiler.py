total = 0
for fn, pairs in JOBS.items():
    p = T + "\\" + fn
    t = io.open(p, encoding="utf-8").read()
    n = 0
    for old, new in pairs:
        c = t.count(old)
        if c:
            t = t.replace(old, new)
            n += c
        else:
            print("  !! %-10s 未匹配：%s" % (fn, old[:44]))
    if n:
        io.open(p, "w", encoding="utf-8", newline="").write(t)
    total += n
    print("  %-10s 替换 %d 处" % (fn, n))

print()
print("  合计 %d 处" % total)

